# Financial Performance Summary

total_revenue = analysis_df["Revenue"].sum()
total_cost = analysis_df["Cost"].sum()
total_profit = analysis_df["GrossProfit"].sum()
total_budget = analysis_df["BudgetAmount"].sum()
total_actual = analysis_df["ActualAmount"].sum()
total_net_sales = analysis_df["NetSales"].sum()

